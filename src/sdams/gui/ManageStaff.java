    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        String id = getSelectedId();
        if (id == null) {
            JOptionPane.showMessageDialog(this,
                    "Select a staff row first.", "No selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Delete staff " + id + "? This cannot be undone.",
                "Confirm Delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        try {
            service.deleteUser(id);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, 
                    ex.getMessage() == null ? "Delete failed." : ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        reload(); 
    }//GEN-LAST:event_deleteBtnActionPerformed
  
    private void applyFilter() {
        List<RowFilter<Object, Object>> filters = new ArrayList<>();

        String search = searchField.getText().trim();
        if (!search.isEmpty()) {
            filters.add(RowFilter.regexFilter("(?i)" + Pattern.quote(search)));
        }

        String type = (String) typeFilterCombo.getSelectedItem();
        if (type != null && !"All Roles".equals(type)) {
            String roleKey;
            String t = type.toLowerCase();
            if (t.equalsIgnoreCase("Instructor")){
                roleKey = "instructor";
            } else if (t.equalsIgnoreCase("Facilities Officer")){
                roleKey = "facilities";
            } else {
                roleKey = "attendance";
            }
            filters.add(RowFilter.regexFilter("(?i)^" + Pattern.quote(roleKey) + "$", 2));
        }
        
        if (filters.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.andFilter(filters));
        }
    }
    
    private String getSelectedId() {
        int viewRow = staffTable.getSelectedRow();
        if (viewRow < 0) return null;
        int modelRow = staffTable.convertRowIndexToModel(viewRow);
        return (String) tableModel.getValueAt(modelRow, 0);
    }
    
