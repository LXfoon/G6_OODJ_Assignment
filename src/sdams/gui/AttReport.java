    private String getStudentName(String studentId){
        String studentName = "";
        for(Student s : allStudent){
            if(s.getId() == null) continue;
            
            if(s.getId().equalsIgnoreCase(studentId) && "Student".equalsIgnoreCase(s.getRole())){
                studentName = s.getName() == null ? "" : s.getName();
                break;
            }
        }
        return studentName;
    }
    
    private String getClassName(String classId){
        String className = "";
        for(ClassSession c : allClasses){
            if(c.getClassId() == null) continue;
            
            if(c.getClassId().equalsIgnoreCase(classId)){
                className = c.getClassName() == null ? "" : c.getClassName();
                break;
            }
        }
        return className;
    }
    
    private void getStatusCount(TreeMap<String, int[]> itemList, String itemId, AttendanceRecord a){
        if(!itemList.containsKey(itemId)){
            itemList.put(itemId, new int[]{0,0,0});
        }

        int[] selectedStatusCount = itemList.get(itemId);

        if(a.getStatus() == AttStatus.Present) {
            selectedStatusCount[0] ++;
        }else if(a.getStatus() == AttStatus.Late){
            selectedStatusCount[1] ++;
        } else if(a.getStatus() == AttStatus.Absent) {
            selectedStatusCount[2] ++;
        }
    }
    
    private void addClassRow(DefaultTableModel classModel){
        for(String classId : classes.keySet()){
            classModel.addRow(new Object[]{
                classId,
                getClassName(classId),
                classes.get(classId)[0],
                classes.get(classId)[1],
                classes.get(classId)[2]
            });
        }
    }
    
    private void addStudentRow(DefaultTableModel studentModel){
        for(String studentId : students.keySet()){
            studentModel.addRow(new Object[]{
                studentId,
                getStudentName(studentId),
                students.get(studentId)[0],
                students.get(studentId)[1],
                students.get(studentId)[2]
            });
        }
    }
