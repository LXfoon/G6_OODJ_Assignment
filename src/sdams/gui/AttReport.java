    @Override
    public void loadData() {
        try{
            allAtt.clear();
            allStudent.clear();
            allClasses.clear();
            FileUtil.read("attendance.txt", allAtt, AttendanceRecord::fromLine);
            FileUtil.read("user.txt", allStudent, Student::fromLine);
            FileUtil.read("class.txt", allClasses, ClassSession::fromLine);
            
        }catch (Exception e){
            System.out.println("Error: "+e.getMessage());
        }
    }

    @Override
    public void applyFilter() {
        classes.clear();
        students.clear();
        DefaultTableModel classModel = (DefaultTableModel) classTable.getModel();
        DefaultTableModel studentModel = (DefaultTableModel) studentTable.getModel();
        classModel.setRowCount(0);
        studentModel.setRowCount(0);
        
        Object studentSel = studentDropdown.getSelectedItem();
        String studFilter = studentSel == null ? "All" : studentSel.toString();

        Object classSel = classDropdown.getSelectedItem();
        String classFilter = classSel == null ? "All" : classSel.toString();
                
        boolean updateStud = false;
        boolean updateClass = false;
        
        for(AttendanceRecord a : allAtt){
            if(a.getAttId() == null || a.getClassId() == null || a.getStudentId() == null) continue;
            String studentName = getStudentName(a.getStudentId()).toLowerCase();
            String className = getClassName(a.getClassId()).toLowerCase();
            
            boolean matchStud = studFilter.equals("All") || studentName.equalsIgnoreCase(studFilter);
            boolean matchClass = classFilter.equals("All") || className.equalsIgnoreCase(classFilter);
            
            if(matchStud && matchClass){
                getStatusCount(classes, a.getClassId(), a);
                getStatusCount(students, a.getStudentId(), a);
                
                if(!studFilter.equals("All")) updateStud = true;
                if(!classFilter.equals("All")) updateClass = true;
            }
        }
        
        if(updateStud){
            addStudentRow(studentModel);
            updateSummary(studentModel);
        } else if(updateClass){
            addClassRow(classModel);
            updateSummary(classModel);
        } else {
            addStudentRow(studentModel);
            addClassRow(classModel);
            updateSummary(classModel);
        }
    }

    @Override
    public void resetFilters() {
        studentDropdown.setSelectedItem("All");
        classDropdown.setSelectedItem("All");
    }

    @Override
    public void populateFilters() {
        studentLists.clear();
        studentDropdown.removeAllItems();
        studentDropdown.addItem("All");
        
        classLists.clear();
        classDropdown.removeAllItems();
        classDropdown.addItem("All");
        
        for(AttendanceRecord a : allAtt){
            if(a.getAttId() == null) continue;
            
            if(a.getStudentId() != null){
                studentLists.add(getStudentName(a.getStudentId()));
            }
            
            if(a.getClassId() != null){
                classLists.add(getClassName(a.getClassId()));
            }
        }
        
        for(String student : studentLists){
            studentDropdown.addItem(student);
        }
        
        for(String classItem : classLists){
            classDropdown.addItem(classItem);
        }
    }

    @Override
    public void updateSummary(DefaultTableModel model) {
        int presentCount = 0, lateCount = 0, absentCount = 0, totalCount = 0;
        
        for(int i=0; i<model.getRowCount(); i++){
            presentCount += Integer.parseInt(model.getValueAt(i, 2).toString());
            lateCount += Integer.parseInt(model.getValueAt(i, 3).toString());
            absentCount += Integer.parseInt(model.getValueAt(i, 4).toString());
        }
        
        totalCount = presentCount + lateCount;
        
        presentCountTxt.setText(String.valueOf(presentCount));
        lateCountTxt.setText(String.valueOf(lateCount));
        absentCountTxt.setText(String.valueOf(absentCount));
        totalCountTxt.setText(String.valueOf(totalCount));
    }
