    private void classTableMouseClicked(java.awt.event.MouseEvent evt) {                                        
        int row = classTable.getSelectedRow();
        String id = classTable.getValueAt(row, 0).toString();

        SelectedClass.setId(id);
        FileUtil.read("attendance.txt", allAtt, AttendanceRecord::fromLine);
        boolean found = false;
        
        for(AttendanceRecord a : allAtt){
            if(id.equalsIgnoreCase(a.getClassId())){
                found = true;
                break;
            }
        }
        
        if(found){
            UpdateAtt update = new UpdateAtt();
            update.setVisible(true);
            this.dispose();
        }else{
            AddAtt add = new AddAtt();
            if(add.getValid()){
                add.setVisible(true);
                this.dispose();    
            } else{
                JOptionPane.showMessageDialog(null, "No bookings found");
                add.dispose();
            }
        }
    }                                       

