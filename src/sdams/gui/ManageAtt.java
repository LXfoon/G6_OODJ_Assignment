    public void searchClass(){
        String query = searchTxt.getText().trim().toLowerCase();
        DefaultTableModel model = (DefaultTableModel) classTable.getModel();
        model.setRowCount(0);
        
        try{
            ArrayList<ClassSession> newList = new ArrayList<>();
            FileUtil.read("class.txt", newList, ClassSession::fromLine);
            
            for(ClassSession c : newList){
                if(c.getClassId() == null) continue;
                if(c.getStatus() != ClassStatus.Completed) continue;
                
                String name = c.getClassName() == null ? "" : c.getClassName().toLowerCase();
                
                if(query.isEmpty() || name.contains(query)){
                    model.addRow(new Object[]{
                        c.getClassId(),
                        c.getClassName(),
                        c.getDiscipline(),
                        c.getDate()
                    });
                }
            }
        }catch(Exception e){
            System.out.println("Error: "+e.getMessage());
        }
    }
