    public AddAtt() {
        initComponents();
        setLocationRelativeTo(null);
        model = (DefaultTableModel) studentTable.getModel();
        
        if (SelectedClass.getId() == null) {
            valid = false;
            return;
        }
        
        try{
            FileUtil.read("booking.txt", allBooking, Booking::fromLine);
            FileUtil.read("user.txt", allStudent, Student::fromLine);
            
            model.setRowCount(0);
            
            boolean found = false;
            for(Booking b : allBooking){
                if(b.getClassId() != null && b.getClassId().equalsIgnoreCase(SelectedClass.getId())){
                    found = true;
                    for(Student s : allStudent){
                        if(s.getId() == null) continue;
                        if(!s.getRole().equals("Student")) continue;

                        if(s.getId().equalsIgnoreCase(b.getStudentId())){
                            model.addRow(new Object[]{
                                s.getId(),
                                s.getName(),
                                "Present"
                            });
                        }
                    }
                }
            }
            
            JComboBox<String> attStatus =  new JComboBox<>();
            attStatus.addItem("Present");
            attStatus.addItem("Late");
            attStatus.addItem("Absent");
            TableColumn targetColumn = studentTable.getColumnModel().getColumn(2);
            targetColumn.setCellEditor(new DefaultCellEditor(attStatus));
            
            valid = found;
        }catch(Exception e){
            System.out.println("Error: "+e.getMessage());
            valid = false;
        }
    }

