    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        if (studentTable.isEditing()) {
            studentTable.getCellEditor().stopCellEditing();  
        }

        DefaultTableModel m = (DefaultTableModel) studentTable.getModel();
        FileUtil.read("attendance.txt", allAtt, AttendanceRecord::fromLine);
        
        int maxNum = 0;
        for(AttendanceRecord a : allAtt){
            String id = a.getAttId();
            if(id != null && id.matches("A\\d+")){
                maxNum = Math.max(maxNum, Integer.parseInt(id.substring(1)));
            }
        }
        for(int i=0; i<m.getRowCount(); i++) {
            String attId = String.format("A%03d", maxNum + i + 1);
            String studentId = m.getValueAt(i, 0).toString();
            String classId = SelectedClass.getId();
            String recordedBy = LoggedIn.getId();
            AttStatus status = AttStatus.fromString(m.getValueAt(i, 2).toString());
            LocalDate recordedDate = LocalDate.now();
            
            AttendanceRecord newAttendance = new AttendanceRecord(attId, studentId, classId, recordedBy, status, recordedDate);
            allAtt.add(newAttendance);
        }
        
        FileUtil.write("attendance.txt", allAtt, AttendanceRecord::toLine);
        JOptionPane.showMessageDialog(null, "Attendance Record Saved!");
        new ManageAtt().setVisible(true);
        this.dispose();
    }//GEN-LAST:event_saveBtnActionPerformed

