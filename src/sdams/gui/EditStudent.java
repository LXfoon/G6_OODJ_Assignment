    public EditStudent(String id) {
        initComponents();
        setLocationRelativeTo(null);

        if (id == null || id.trim().isEmpty()) {
            SwingUtilities.invokeLater(() -> {
                JOptionPane.showMessageDialog(this,
                        "No student id supplied to EditStudent.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                goBack();
            });
            return;
        }

        this.editingId = id.trim();
        service.loadUser();
        loadStudent(editingId);
    }
    
    private void loadStudent(String id) {
        Student stu = service.findById(id);
        if (stu == null) {
            SwingUtilities.invokeLater(() -> {
                JOptionPane.showMessageDialog(this,
                        "Student not found: " + id, "Error",
                        JOptionPane.ERROR_MESSAGE);
                goBack();
            });
            return;
        }

        oriName  = stu.getName();
        oriEmail = stu.getEmail();
        oriPhone = stu.getPhoneNum();

        pageTitle.setText("Edit Student: " + oriName);
        nameField.setText(oriName);
        emailField.setText(oriEmail);
        phoneField.setText(oriPhone);
    }

