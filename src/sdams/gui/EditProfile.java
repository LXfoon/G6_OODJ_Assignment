    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        if (user == null) {
            JOptionPane.showMessageDialog(this, "User not found: " + userId);
            return;
        }
        
        String name = nameTxt.getText().trim();
        String email = emailTxt .getText().trim();
        String password = new String(pswTxt.getPassword());
        String phone = phoneTxt.getText().trim();
            
        ArrayList<String> lines = new ArrayList<>();
        FileUtil.read(USER_FILE, lines, s -> s);
        
        ArrayList<User> allUsers = new ArrayList<>();
        int currentIndex = -1;
        
        for (int i = 0; i < lines.size(); i++) {
            String[] parts = lines.get(i).split("\\|", -1);
            if (parts.length < 6) {
                continue;
            }

            User u = buildUser(parts);
            if (u == null) {
                continue;
            }
            allUsers.add(u);

            if (parts[0].trim().equals(userId)) {
                currentIndex = i;
            }
        }
        
        if (currentIndex == -1) {
            JOptionPane.showMessageDialog(this, "User line not found: " + userId);
            return;
        }
        
        try {
            Validator.userValidator(name, email, password, phone);
            Validator.inputFieldChecker(List.of(name, email, password, phone));
            Validator.dupEmailChecker(email, userId, allUsers);
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this,
                    ex.getMessage() == null ? "Invalid input." : ex.getMessage(),
                    "Validation", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        user.setName(name);
        user.setEmail(email);
        user.setPassword(password);
        user.setPhoneNum(phone);
        
        String newLine = user.toLine();
        
        lines.set(currentIndex, newLine);
        FileUtil.write(USER_FILE, lines, s -> s);

        JOptionPane.showMessageDialog(this, "Profile updated.");
        goBack();
    }//GEN-LAST:event_saveBtnActionPerformed

